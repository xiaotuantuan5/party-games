/** 这张牌在某个主题下的解读 */
export function cardReading(card: TarotCard, reversed: boolean, topic: TarotTopic): string[] {
  const lines = [reversed ? card.rev : card.up];
  if (card.suit) {
    lines.push(SUIT_TOPIC_TIPS[topic][card.suit]);
  } else if (topic === "love" && card.love) {
    lines.push(`感情上：${card.love}`);
  } else if ((topic === "work" || topic === "money") && card.work) {
    lines.push(`${topic === "work" ? "事业学业" : "财运"}上：${card.work}`);
  }
  return lines;
}

/** 整体解读：看大阿卡纳的比例、哪种元素最多、正逆位多少 */
export function summarize(cards: DrawnCard[]): string[] {
  const out: string[] = [];
  const full = cards.map((c) => TAROT_DECK[c.id]!);
  const n = cards.length;
  const majors = full.filter((c) => c.suit === null).length;
  const reversed = cards.filter((c) => c.reversed).length;

  if (n === 1) {
    const c = full[0]!;
    out.push(
      cards[0]!.reversed
        ? `「${c.name}」逆位，提醒你留意：${c.keywordsRev}。`
        : `「${c.name}」正位，关键词是：${c.keywordsUp}。`,
    );
    out.push(c.suit === null ? "抽到大阿卡纳，这件事对你来说分量不轻。" : `这是一张${SUITS[c.suit].name}牌，和${SUITS[c.suit].theme}有关。`);
    return out;
  }

  if (majors >= Math.ceil(n / 2)) out.push(`${n} 张里有 ${majors} 张大阿卡纳，这件事受大环境和人生节点影响比较大，是很重要的一课。`);
  else if (majors === 0) out.push("全是小阿卡纳，说明事情主要在日常层面，靠你自己的选择就能改变。");

  const counts = new Map<TarotSuit, number>();
  for (const c of full) if (c.suit) counts.set(c.suit, (counts.get(c.suit) ?? 0) + 1);
  const top = [...counts].sort((a, b) => b[1] - a[1])[0];
  if (top && top[1] >= 2) {
    const s = SUITS[top[0]];
    out.push(`${s.name}（${s.element}）出现了 ${top[1]} 次，重点落在${s.theme}上。`);
  }

  if (reversed === 0) out.push("全部是正位，能量很顺，放心往前走。");
  else if (reversed > n / 2) out.push(`有 ${reversed} 张逆位，事情还卡在某些地方，先处理心里的阻力，再去推动外面的事。`);
  else out.push(`正位 ${n - reversed} 张、逆位 ${reversed} 张，整体偏顺，留意逆位牌提到的地方就好。`);

  const last = cards[n - 1]!;
  const lastCard = full[n - 1]!;
  out.push(
    last.reversed
      ? `最后一张「${lastCard.name}」是逆位，结果还没定，现在调整还来得及。`
      : `最后一张「${lastCard.name}」是正位，走向是积极的。`,
  );
  return out;
}
